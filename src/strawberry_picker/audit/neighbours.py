"""How much of each training crop shows *other* berries (ADR 0008 diagnostic).

Needs only the silver manifest (boxes and image sizes), no images and no model, so it runs
anywhere. When the statistical audit has out-of-fold predictions, it also breaks the
probe's error rate down by overlap: if errors climb with overlap, neighbours are hurting.

Writes ``reports/dataset-audit/neighbours/``: ``per_crop.csv``, ``summary.csv``,
``error_by_overlap.csv`` (when predictions exist) and ``neighbours.md``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from strawberry_picker.audit.report import _markdown_table, audit_frame
from strawberry_picker.data.crops import CropPolicy, crop_box, neighbour_overlap

TABLE_COLUMNS = ("crop_id", "source_name", "label", "n_neighbours", "neighbour_overlap")
BUCKETS = ("0", "0-10%", "10-25%", ">25%")


def _bbox(value) -> tuple[float, ...] | None:
    if value is None or isinstance(value, float):
        return None
    return tuple(float(v) for v in value)


def overlap_table(manifest: pd.DataFrame, policy: CropPolicy) -> pd.DataFrame:
    """One row per audited silver crop: how many neighbours it has and how much they cover."""
    frame = audit_frame(manifest)
    overlaps = []
    for bbox, width, height, others in zip(
        frame.bbox, frame.width, frame.height, frame.neighbour_bboxes, strict=True
    ):
        box = _bbox(bbox)
        crop = crop_box(box, int(width), int(height), policy.padding)
        overlaps.append(neighbour_overlap(crop, box, others))
    return pd.DataFrame(
        {
            "crop_id": frame.crop_id,
            "source_name": frame.source_name,
            "label": frame.label,
            "n_neighbours": [len(n) for n in frame.neighbour_bboxes],
            "neighbour_overlap": np.asarray(overlaps, dtype=float),
        }
    )[list(TABLE_COLUMNS)]


def overlap_summary(table: pd.DataFrame) -> pd.DataFrame:
    """Per source and label: share of crops with any neighbour in view, > 10 % and > 25 %."""
    overlap = table.neighbour_overlap
    return (
        table.assign(
            any_=overlap > 0, over_10=overlap > 0.10, over_25=overlap > 0.25, value=overlap
        )
        .groupby(["source_name", "label"])
        .agg(
            n=("crop_id", "size"),
            share_any=("any_", "mean"),
            share_over_10=("over_10", "mean"),
            share_over_25=("over_25", "mean"),
            mean_overlap=("value", "mean"),
        )
        .reset_index()
    )


def _bucket(overlap: pd.Series) -> pd.Series:
    bins = [-np.inf, 0.0, 0.10, 0.25, np.inf]
    return pd.cut(overlap, bins=bins, labels=list(BUCKETS), right=True)


def error_by_overlap(table: pd.DataFrame, issues: pd.DataFrame) -> pd.DataFrame:
    """Out-of-fold error and label-issue rate per task and overlap bucket.

    ``issues`` is the audit's ``label_issues`` frame (``crop_id, task, given, predicted,
    is_issue``).
    """
    merged = table.merge(issues, on="crop_id", how="inner")
    merged["bucket"] = _bucket(merged.neighbour_overlap)
    merged["error"] = merged.predicted != merged.given
    merged["flagged"] = merged.is_issue.astype(bool)
    out = (
        merged.groupby(["task", "bucket"], observed=True)
        .agg(n=("crop_id", "size"), error_rate=("error", "mean"), flagged_rate=("flagged", "mean"))
        .reset_index()
    )
    out["bucket"] = out.bucket.astype(str)
    return out


def write_neighbour_report(
    table: pd.DataFrame, out_dir: Path, *, issues: pd.DataFrame | None = None
) -> Path:
    """Write the neighbour diagnostic under ``out_dir/neighbours``; return ``neighbours.md``."""
    target = out_dir / "neighbours"
    target.mkdir(parents=True, exist_ok=True)
    table.to_csv(target / "per_crop.csv", index=False)
    summary = overlap_summary(table)
    summary.to_csv(target / "summary.csv", index=False)
    sections = [
        "# Neighbour overlap in training crops",
        "Generated by `scripts/crop_overlap.py` or `scripts/dataset_audit.py`. "
        "Overlap = share of the padded crop covered by other annotated fruit, outside the "
        "fruit's own box. What to do about it: ADR 0008.",
        "## Per source and label",
        _markdown_table(summary),
    ]
    if issues is not None and "predicted" in issues:
        buckets = error_by_overlap(table, issues)
        buckets.to_csv(target / "error_by_overlap.csv", index=False)
        sections += [
            "## Out-of-fold error rate by overlap",
            "If the error rate climbs with overlap, neighbours confuse the probe.",
            _markdown_table(buckets),
        ]
    path = target / "neighbours.md"
    path.write_text("\n\n".join(sections) + "\n")
    return path
